/**
 * Versioned vectors for project 3 (ts-stack) to reproduce (spec 6.10): the connect proof, the
 * inbox record, result and close event, the `brc185:*` envelopes and the error-codec objects for
 * codes 5, 6 and 7 and for `ConnectionError`. They are built here from fixed inputs by the core's
 * own encoders, and compared with `fixtures/bridge-core-vectors.json` as RFC 8785 (JCS) text, so
 * the comparison is byte for byte on the canonical form and independent of how the file is formatted. A change to
 * any encoder makes this fail until the fixture is regenerated on purpose (flip `WRITE` once,
 * review the diff, flip it back) and `version` is raised if the change is not backwards compatible.
 */
import { ed25519 } from '@noble/curves/ed25519.js'
import { WERR_INSUFFICIENT_FUNDS, WERR_INVALID_PARAMETER, WERR_REVIEW_ACTIONS } from '@bsv/sdk'
import * as fs from 'fs'
import * as path from 'path'
import { b64uEncode } from '../../core/bridge/protocol/base64url'
import { connectionError } from '../../core/bridge/protocol/connectionError'
import {
  connectPreimage,
  signConnect,
  verifyConnectProof,
  type Descriptor
} from '../../core/bridge/protocol/descriptor'
import { encodeWalletError } from '../../core/bridge/protocol/errorCodec'
import {
  parseXdmEnvelope,
  xdmClosed,
  xdmError,
  xdmResult,
  type InboxCloseEvent,
  type InboxRecord,
  type InboxResult
} from '../../core/bridge/protocol/envelopes'
import { canonicalize } from '../../core/bridge/protocol/json'

const WRITE = false
const FIXTURE = path.join(__dirname, 'fixtures', 'bridge-core-vectors.json')

const SEED = new Uint8Array(32).map((_, i) => i + 1)
const PUB = ed25519.getPublicKey(SEED)
const signer = { sign: async (m: Uint8Array) => ed25519.sign(m, SEED) }
const hex = (b: Uint8Array) => Buffer.from(b).toString('hex')

const ORIGIN = 'https://app.example'
const CHALLENGE = b64uEncode(new Uint8Array(32).map((_, i) => 255 - i))
const EPOCH = '22222222-2222-4222-8222-222222222222'
const INSTANCE = '11111111-1111-4111-8111-111111111111'
const REQUEST = '33333333-3333-4333-8333-333333333333'

const descriptor: Descriptor = {
  version: 1,
  instanceId: INSTANCE,
  name: 'Example Wallet',
  instanceLabel: '',
  vendor: 'example.wallet',
  continuityKey: b64uEncode(PUB),
  endpoints: [{ id: 'xdm', type: 'xdm', address: 'window' }]
}

async function build() {
  const connect = { origin: ORIGIN, epoch: EPOCH, challenge: CHALLENGE, descriptor }
  const response = await signConnect(signer, connect)

  const record: InboxRecord = {
    v: 1,
    id: REQUEST,
    kind: 'invoke',
    epoch: EPOCH,
    instanceId: INSTANCE,
    continuityKey: descriptor.continuityKey,
    origin: ORIGIN,
    accountContext: 'a'.repeat(64),
    walletRevision: '3',
    boundAt: 1_700_000_000_000,
    method: 'getHeight',
    args: {},
    createdAt: 1_700_000_100_000,
    notAfter: 1_700_000_400_000
  }
  const disconnect: InboxRecord = { ...record, id: '44444444-4444-4444-8444-444444444444', kind: 'disconnect' }
  delete disconnect.method
  delete disconnect.args

  const reviewActions = encodeWalletError(
    new WERR_REVIEW_ACTIONS(
      [{ txid: 'aa'.repeat(32), status: 'doubleSpend', competingTxs: ['bb'.repeat(32)] } as never],
      [{ txid: 'aa'.repeat(32), status: 'failed' } as never],
      'aa'.repeat(32),
      [1, 2, 3],
      [`${'aa'.repeat(32)}.0`]
    )
  )
  const invalidParameter = encodeWalletError(new WERR_INVALID_PARAMETER('basket', 'a string'))
  const insufficientFunds = encodeWalletError(new WERR_INSUFFICIENT_FUNDS(1000, 250))
  const providerChanged = connectionError(
    'PROVIDER_CHANGED',
    'The wallet changed since this page connected',
    'not-sent',
    {
      epoch: EPOCH,
      cause: 'account-changed'
    }
  )

  const results: InboxResult[] = [
    { v: 1, id: REQUEST, ok: true, result: { height: 850000 } },
    { v: 1, id: REQUEST, ok: false, error: invalidParameter },
    { v: 1, id: REQUEST, ok: false, error: providerChanged }
  ]
  const closeEvents: InboxCloseEvent[] = [
    { v: 1, closeSeq: 1, instanceId: INSTANCE, epoch: EPOCH, reason: 'account-changed' },
    { v: 1, closeSeq: 2, instanceId: INSTANCE, epoch: EPOCH, reason: 'lost', notifyPage: false }
  ]

  return {
    version: 1,
    note: 'Generated by __tests__/bridge/bridgeCoreVectors.test.ts. Project 3 must reproduce every value.',
    ed25519: { seedHex: hex(SEED), publicKeyHex: hex(PUB) },
    connectProof: {
      input: connect,
      preimageHex: hex(connectPreimage(connect)),
      jcsUtf8: canonicalize(connect),
      response
    },
    inbox: { record, disconnectRecord: disconnect, results, closeEvents },
    envelopes: {
      connect: {
        type: 'brc185:connect',
        version: 1,
        instanceId: INSTANCE,
        continuityKey: descriptor.continuityKey,
        epoch: EPOCH,
        challenge: CHALLENGE
      },
      connected: { type: 'brc185:connected', version: 1, proof: response },
      connectionError: { type: 'brc185:connection-error', version: 1, epoch: EPOCH, error: providerChanged },
      invoke: {
        type: 'brc185:invoke',
        version: 1,
        instanceId: INSTANCE,
        epoch: EPOCH,
        id: REQUEST,
        method: 'getHeight',
        params: {}
      },
      result: xdmResult(INSTANCE, EPOCH, REQUEST, { height: 850000 }),
      error: xdmError(INSTANCE, EPOCH, REQUEST, invalidParameter),
      closed: xdmClosed(INSTANCE, EPOCH, 'revoked')
    },
    errorCodec: {
      code5ReviewActions: reviewActions,
      code6InvalidParameter: invalidParameter,
      code7InsufficientFunds: insufficientFunds,
      connectionErrors: [
        providerChanged,
        connectionError('RESOURCE_LIMIT', 'Request too large', 'not-sent', { epoch: EPOCH }),
        connectionError('CONNECTION_CLOSED', 'The wallet restarted during the call', 'unknown', { epoch: EPOCH })
      ]
    }
  }
}

describe('bridge core vectors (spec 6.10)', () => {
  it('are re-derived byte for byte from the current encoders', async () => {
    const built = await build()
    const text = JSON.stringify(built, null, 2) + '\n'
    if (WRITE) fs.writeFileSync(FIXTURE, text)
    expect(canonicalize(JSON.parse(fs.readFileSync(FIXTURE, 'utf8')))).toBe(canonicalize(built))
  })

  it('the connect proof verifies against the identity key, and every envelope parses', async () => {
    const v = JSON.parse(fs.readFileSync(FIXTURE, 'utf8'))
    const d = verifyConnectProof(v.connectProof.response, {
      origin: ORIGIN,
      epoch: EPOCH,
      challenge: CHALLENGE,
      expectedIdentity: { instanceId: INSTANCE, continuityKey: descriptor.continuityKey }
    })
    expect(d.name).toBe('Example Wallet')
    for (const key of ['connected', 'connectionError', 'invoke', 'result', 'error', 'closed', 'connect']) {
      expect(parseXdmEnvelope(v.envelopes[key])).toBeDefined()
    }
  })
})
